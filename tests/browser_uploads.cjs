const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

(async()=>{
  const url=process.env.RAG_URL||'http://127.0.0.1:8091';
  assert.notEqual(url,'http://127.0.0.1:8090','Use an isolated sandbox');
  const sandbox=process.env.RAG_SANDBOX;
  assert.ok(sandbox);
  const output=path.join(sandbox,'screenshots');fs.mkdirSync(output,{recursive:true});
  const browser=await chromium.launch({headless:true,args:['--no-sandbox']});
  const errors=[];
  try{
    const page=await browser.newPage({viewport:{width:1440,height:1000}});
    page.on('pageerror',error=>errors.push(error.message));
    await page.goto(url+'/library');
    await page.locator('#pdf-file').setInputFiles(path.join(sandbox,'library-native.pdf'));
    await page.locator('#title').fill('网页上传验收研报');
    await page.locator('#org').fill('测试证券');
    await page.locator('#publish-date').fill('2026-09-07');
    await page.locator('#visual').uncheck();
    const uploaded=page.waitForResponse(r=>r.url()===url+'/uploads'&&r.request().method()==='POST');
    await page.locator('#upload-button').click();
    const response=await uploaded;assert.equal(response.status(),202);const job=await response.json();
    const row=page.locator(`tr[data-upload-id="${job.id}"]`);
    await row.getByRole('button',{name:'校对与入库'}).waitFor({timeout:90000});
    await page.screenshot({path:path.join(output,'library-desktop.png'),fullPage:true});
    await row.getByRole('button',{name:'校对与入库'}).click();
    await page.locator('#review-dialog').waitFor({state:'visible'});
    await page.waitForFunction(()=>document.getElementById('page-image').complete&&document.getElementById('page-image').naturalWidth>0);
    const editor=page.locator('#blocks textarea').first();
    const original=await editor.inputValue();await editor.fill(original+'（已校对）');
    await page.locator('#save-review').click();
    await page.waitForFunction(()=>document.getElementById('save-state').textContent==='校对已保存');
    await page.locator('#page-select').selectOption('2');
    await page.waitForFunction(()=>document.getElementById('page-image').src.includes('/pages/2/'));
    await page.getByRole('button',{name:'定位原文'}).first().click();
    await page.waitForFunction(()=>{const img=document.getElementById('page-image');return img.src.includes('block_id=')&&img.complete&&img.naturalWidth>0});
    const geometry=await page.locator('#page-image').evaluate(img=>{const c=document.createElement('canvas');c.width=img.naturalWidth;c.height=img.naturalHeight;const x=c.getContext('2d');x.drawImage(img,0,0);const d=x.getImageData(0,0,c.width,c.height).data;let green=0;for(let i=0;i<d.length;i+=4)if(d[i+1]>d[i]+15&&d[i+1]>d[i+2]+10)green++;return {width:c.width,height:c.height,green}});
    assert.ok(geometry.green>100,JSON.stringify(geometry));
    await page.screenshot({path:path.join(output,'review-desktop.png'),fullPage:true});
    await page.locator('#publish').click();
    await page.locator('#review-dialog').waitFor({state:'hidden',timeout:20000});
    await row.getByRole('button',{name:'查看解析'}).waitFor({timeout:120000});
    await page.setViewportSize({width:390,height:844});
    await page.screenshot({path:path.join(output,'library-mobile.png'),fullPage:true});
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
    await row.getByRole('button',{name:'查看解析'}).click();
    await page.locator('#review-dialog').waitFor({state:'visible'});
    await page.waitForFunction(()=>document.getElementById('page-image').complete&&document.getElementById('page-image').naturalWidth>0);
    assert.equal(await page.locator('#blocks textarea').first().inputValue(),original+'（已校对）');
    assert.equal(await page.locator('#publish').isDisabled(),true);
    assert.equal(await page.evaluate(()=>{const d=document.getElementById('review-dialog');return d.scrollWidth<=d.clientWidth}),true);
    await page.screenshot({path:path.join(output,'review-mobile.png'),fullPage:true});
    assert.deepEqual(errors,[]);
    const result={upload_id:job.id,geometry,errors,checks:['browser_upload','review_edit','table_page','highlight_pixels','publish','mobile','immutable_indexed_review']};
    fs.writeFileSync(path.join(sandbox,'browser-acceptance.json'),JSON.stringify(result,null,2));
    console.log(JSON.stringify(result,null,2));
  }finally{await browser.close()}
})().catch(error=>{console.error(error);process.exit(1)});
